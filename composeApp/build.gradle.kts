// Coverage of the shared code from the Android host tests (JVM, in-memory SQLite).
// AGP writes the execution data because `enableCoverage = true` above; Kover cannot see this
// task with the Android KMP library plugin, so the report is built with JaCoCo directly.
val coverageReport by tasks.registering(JacocoReport::class) {
    group = "verification"
    description = "Coverage report for the Android host tests: build/reports/jacoco/coverageReport"
    dependsOn("testAndroidHostTest")
    executionData(
        layout.buildDirectory.file("outputs/unit_test_code_coverage/androidHostTest/testAndroidHostTest.exec"),
    )
    classDirectories.setFrom(
        fileTree(layout.buildDirectory.dir("classes/kotlin/android/main")) {
            // Generated by SQLDelight; the repositories that use it are what we test.
            exclude("app/cardfilter/data/db/**")
        },
    )
    sourceDirectories.setFrom(files("src/commonMain/kotlin", "src/androidMain/kotlin"))
    reports {
        xml.required = true
        html.required = true
    }
}
